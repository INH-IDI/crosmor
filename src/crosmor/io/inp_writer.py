"""Writer for legacy CROSMOR .inp input files."""

from pathlib import Path
from typing import Union
from crosmor.models.config import SimulationConfig


def write_inp(config: SimulationConfig, file_path: Union[str, Path]) -> None:
    """Export a SimulationConfig instance to a CROSMOR .inp format file."""
    path = Path(file_path)
    lines = []

    lines.append(f"* CROSMOR input file generated by CROSMOR 2026: {config.title}")
    lines.append("* Options output hydrodynamics 0/1/2")
    lines.append(f"  {config.iprint}")

    # Tide
    lines.append("* table length of tidal schematization (ntide)")
    lines.append(f"  {len(config.tide_series)}")
    lines.append("*   T (sec)    Vnul1(m/s)  Vnul2(m/s)  Ws(m)")
    for tp in config.tide_series:
        lines.append(f"  {tp.time:10.1f}  {tp.vnul1:10.4f}  {tp.vnul2:10.4f}  {tp.ws:10.4f}")

    # Bathymetry
    lines.append("* table length of bottom schematization (nhmsl)")
    lines.append(f"  {len(config.bathymetry)}")
    lines.append("*   X(m)  HMSL(m) NSTAP")
    for bp in config.bathymetry[:-1]:
        nstap = bp.nstap if bp.nstap is not None else 10
        lines.append(f"  {bp.x:10.2f}  {bp.hmsl:10.3f}  {nstap:5d}")
    last_bp = config.bathymetry[-1]
    lines.append(f"  {last_bp.x:10.2f}  {last_bp.hmsl:10.3f}")

    # Cutoff depth & beach
    lines.append("* minimum water depth for calculation hgrens, 1/0 beach")
    lines.append(f"  {config.hgrens:10.3f}  {config.istrand:5d}")

    # Storm surge
    lines.append("* table length storm (wind-induced) set-up HSTORM")
    lines.append(f"  {len(config.storm_series)}")
    lines.append("*   T(s)    HSTORM(m)")
    for sp in config.storm_series:
        lines.append(f"  {sp.time:10.1f}  {sp.hstorm:10.4f}")

    # Wave options
    lines.append("* option=1/2/-2 (igolf)")
    lines.append(f"  {config.igolf}")
    if config.igolf == 1:
        lines.append(f"  {len(config.wave_classes)}")
        lines.append("*    H     T    P    TETA   W10")
        for i, wc in enumerate(config.wave_classes):
            if i == 0:
                lines.append(f"  {wc.h:8.3f}  {wc.t:8.2f}  {wc.p:8.4f}  {wc.teta:8.2f}  {wc.w10:8.2f}")
            else:
                lines.append(f"  {wc.h:8.3f}  {wc.t:8.2f}  {wc.p:8.4f}  {wc.teta:8.2f}")
    elif config.igolf == 2:
        lines.append(f"  {config.nh_wave_classes}")
        lines.append(f"  {len(config.wave_series)}")
        lines.append("*    TIME(s) HRMS    T   TETA W10")
        for wt in config.wave_series:
            lines.append(f"  {wt.time:10.1f}  {wt.hrms:8.3f}  {wt.t:8.2f}  {wt.teta:8.2f}  {wt.w10:8.2f}")
    elif config.igolf == -2:
        lines.append(f"  {config.nh_wave_classes}")
        wfile = config.wave_file or "awavedat.inp"
        lines.append(f"{wfile}")

    # Hydro params
    lines.append("* Switch1 ROLLERcoef COEF6 CLH CSW Switch2 Switch3 SL SEF Switch4")
    h = config.hydro
    lines.append(
        f"  {h.switch1_asymmetry:3d}  {h.roller_coef:8.2f}  {h.coef6:8.2f}  {h.clh:8.2f}  {h.csw:8.2f}  "
        f"{h.switch2_nielsen:3d}  {h.switch3_phaselag:3d}  {h.sl_dune_slope:8.1f}  {h.sef1:8.2f}  {h.switch4_longwaves:3d}"
    )
    lines.append("* COEFSR GAMMA coef5 ELS(m2/s) Niteration SW")
    lines.append(f"  {h.coefsr:8.3f}  {h.gamma:8.2f}  {h.coef5:8.2f}  {h.els:8.2f}  {h.nit:5d}  {h.sw:8.2f}")

    # Morpho params
    m = config.morpho
    lines.append("* options output transport 0/1/2 and NOUT")
    lines.append(f"  {m.iprant:3d}  {m.nout:5d}")
    lines.append("* DL(m) RHOS(kg/m3) POR(-) facbed(-) facsusc(-) facsusw(-) T-END (s)")
    lines.append(
        f"  {m.dl:8.3f}  {m.rhos:8.1f}  {m.por:8.3f}  {m.facbed:8.3f}  {m.facsusc:8.3f}  {m.facsusw:8.3f}  {m.tend:12.1f}"
    )
    lines.append("* factime facbed facgrain")
    lines.append(f"  {m.factime:8.3f}  {m.facbed_smooth:8.3f}  {m.facgrain_smooth:8.3f}")

    # Sediment metadata
    lines.append("* NFR NSED TE SA")
    lines.append(f"  {config.nfr:3d}  {config.nsed:5d}  {m.water_temp:8.2f}  {m.salinity:8.2f}")
    lines.append("* X(m) RC(m) RW(m) PMUD(%) FRIP")
    for sp in config.sediment_points:
        lines.append(f"  {sp.x:10.2f}  {sp.rc:10.5f}  {sp.rw:10.5f}  {sp.pmud:8.2f}  {sp.frip:8.2f}")

    # Diameters
    lines.append("* Grain diameters (m)")
    d_strs = [f"{d:10.6f}" for d in m.grain_diameters]
    lines.append("  " + "  ".join(d_strs))

    # Fraction matrix
    lines.append("* X and Fractions (sum + pmud/100 = 1.0)")
    for sp in config.sediment_points:
        row = [f"{sp.x:10.2f}"] + [f"{fr:8.4f}" for fr in sp.fractions]
        lines.append("  " + "  ".join(row))

    # Contours
    lines.append("* Ndc")
    lines.append(f"  {len(m.depth_contours)}")
    if m.depth_contours:
        lines.append("  " + "  ".join(f"{c:8.2f}" for c in m.depth_contours))

    lines.append("* Ndx")
    lines.append(f"  {len(m.x_contours)}")
    if m.x_contours:
        lines.append("  " + "  ".join(f"{x:8.1f}" for x in m.x_contours))

    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
